export const generatedTypeHeader =
  "// Generated by scripts/office-v2-contracts-generate.mjs. Do not edit.";

const repositoryRoot = resolve(import.meta.dirname, "..");
const webFeatureRoot = "apps/web/src/features/office-v2";
const sourceExtensions = new Set([
  ".cjs", ".cts", ".js", ".jsx", ".mjs", ".mts", ".ts", ".tsx",
]);
const runtimeDependencySections = ["dependencies", "optionalDependencies", "peerDependencies"];
const dependencySections = [...runtimeDependencySections, "devDependencies"];
const ignoredDirectories = new Set(["node_modules", "dist", "coverage"]);

function normalizePath(value) {
  return value.replaceAll("\\", "/").replace(/^\.\//, "");
}

function diagnostic(code, path, message, context = {}) {
  return { code, owner: "architecture", version: 1, path, message, context };
}

function collectFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory).flatMap((name) => {
    if (ignoredDirectories.has(name)) return [];
    const absolute = join(directory, name);
    return statSync(absolute).isDirectory() ? collectFiles(absolute) : [absolute];
  });
}

function findOwningRule(projectPath) {
  return officeV2PackageRules.find(
    (rule) => projectPath === rule.root || projectPath.startsWith(`${rule.root}/`),
  );
}

function findOfficePackage(specifier) {
  return officeV2PackageRules.find(
    (rule) => specifier === rule.name || specifier.startsWith(`${rule.name}/`),
  );
}

function forbiddenSpecifierKind(specifier) {
  if (/^(?:react|react-dom)(?:\/|$)/.test(specifier)) return "react";
  if (/^(?:pixi\.js(?:\/|$)|@pixi\/|three(?:\/|$)|@react-three\/|phaser(?:\/|$)|konva(?:\/|$))/.test(specifier)) {
    return "renderer";
  }
  if (/^@affiliate-ops\/(?:database|storage)(?:\/|$)/.test(specifier)) return "persistence";
  if (/^@affiliate-ops\/automation-runner(?:\/|$)/.test(specifier)) return "automation-runner";
  if (/^@affiliate-ops\/(?:api|discord-bot|web)(?:\/|$)/.test(specifier)) return "application";
  if (/^@affiliate-ops\/brain(?:\/|$)/.test(specifier)) return "provider";
  if (/(?:^|[-/])(?:connectors?|providers?)(?:[-/]|$)/i.test(specifier)) return "provider";
  return null;
}

function forbiddenProjectModuleKind(projectPath) {
  if (/(?:^|\/)connectors?(?:\/|\.[^/]+$)/i.test(projectPath)) return "connector";
  if (/(?:^|\/)providers?(?:\/|\.[^/]+$)/i.test(projectPath)) return "provider";
  if (/(?:^|\/)renderers?(?:\/|\.[^/]+$)/i.test(projectPath)) return "renderer";
  if (/(?:^|\/)database(?:\/|\.[^/]+$)/i.test(projectPath)) return "persistence";
  return null;
}

export function extractModuleSpecifiers(source) {
  return [...new Set(
    analyzeModuleLoads(source)
      .filter((entry) => entry.literal)
      .map((entry) => entry.specifier),
  )];
}

function validateManifest(rule, record, diagnostics) {
  const manifestPath = `${rule.root}/package.json`;
  if (!record) {
    diagnostics.push(diagnostic(
      "architecture.office-v2.missing-manifest",
      manifestPath,
      "Approved Office package is missing package.json.",
      { package: rule.name },
    ));
    return;
  }
  if (record.parseError) {
    diagnostics.push(diagnostic(
      "architecture.office-v2.invalid-manifest",
      manifestPath,
      "Office package manifest is not valid JSON.",
      { reason: record.parseError },
    ));
    return;
  }
  const manifest = record.value ?? record;
  if (manifest.name !== rule.name) {
    diagnostics.push(diagnostic(
      "architecture.office-v2.manifest-name",
      manifestPath,
      `Expected package name ${rule.name}.`,
      { actual: manifest.name ?? null, expected: rule.name },
    ));
  }

  const declaredRuntime = manifest.dependencies ?? {};
  for (const required of rule.dependencies) {
    if (!(required in declaredRuntime)) {
      diagnostics.push(diagnostic(
        "architecture.office-v2.missing-dependency",
        manifestPath,
        `Required dependency ${required} is missing from dependencies.`,
        { package: rule.name, dependency: required },
      ));
    } else if (declaredRuntime[required] !== "0.1.0") {
      diagnostics.push(diagnostic(
        "architecture.office-v2.dependency-version",
        manifestPath,
        `Workspace dependency ${required} must use version 0.1.0.`,
        { actual: declaredRuntime[required], dependency: required },
      ));
    }
  }

  for (const section of dependencySections) {
    for (const dependency of Object.keys(manifest[section] ?? {})) {
      const isDevOnly = section === "devDependencies";
      const isAllowed = rule.dependencies.includes(dependency);
      const forbiddenKind = forbiddenSpecifierKind(dependency);
      if (forbiddenKind) {
        diagnostics.push(diagnostic(
          "architecture.office-v2.forbidden-dependency",
          manifestPath,
          `Office packages cannot depend on ${dependency}.`,
          { dependency, forbiddenKind, package: rule.name, section },
        ));
      } else if (findOfficePackage(dependency) && !isAllowed) {
        diagnostics.push(diagnostic(
          "architecture.office-v2.dependency-direction",
          manifestPath,
          `Dependency ${dependency} is outside the approved graph for ${rule.name}.`,
          { allowed: rule.dependencies, dependency, package: rule.name, section },
        ));
      } else if (dependency.startsWith("@affiliate-ops/") && !isAllowed) {
        diagnostics.push(diagnostic(
          "architecture.office-v2.dependency-direction",
          manifestPath,
          `Workspace dependency ${dependency} is outside the approved graph for ${rule.name}.`,
          { allowed: rule.dependencies, dependency, package: rule.name, section },
        ));
      } else if (!isDevOnly && !isAllowed) {
        diagnostics.push(diagnostic(
          "architecture.office-v2.dependency-not-allowed",
          manifestPath,
          `Runtime dependency ${dependency} is not approved for ${rule.name}.`,
          { allowed: rule.dependencies, dependency, package: rule.name, section },
        ));
      } else if (runtimeDependencySections.includes(section) && section !== "dependencies" && isAllowed) {
        diagnostics.push(diagnostic(
          "architecture.office-v2.dependency-section",
          manifestPath,
          `Workspace dependency ${dependency} must be declared in dependencies.`,
          { dependency, package: rule.name, section },
        ));
      }
    }
  }
}

function validatePackageImport(file, rule, specifier, diagnostics) {
  if (specifier.includes("\\")) {
    diagnostics.push(diagnostic(
      "architecture.office-v2.noncanonical-specifier",
      file.path,
      "Office package module specifiers must use forward slashes without escapes.",
      { package: rule.name, specifier },
    ));
    return;
  }
  if (specifier.startsWith(".")) {
    const target = normalizePath(posix.normalize(posix.join(posix.dirname(file.path), specifier)));
    if (target !== rule.root && !target.startsWith(`${rule.root}/`)) {
      diagnostics.push(diagnostic(
        "architecture.office-v2.relative-boundary",
        file.path,
        `Relative import escapes ${rule.root}.`,
        { package: rule.name, specifier, target },
      ));
    } else {
      const forbiddenKind = forbiddenProjectModuleKind(target);
      if (forbiddenKind) {
        diagnostics.push(diagnostic(
          "architecture.office-v2.forbidden-import",
          file.path,
          `Office packages cannot import local ${forbiddenKind} implementations.`,
          { forbiddenKind, package: rule.name, specifier, target },
        ));
      }
    }
    return;
  }
  if (specifier.startsWith("node:") || specifier === rule.name) return;

  const matchedOfficePackage = findOfficePackage(specifier);
  if (matchedOfficePackage && specifier !== matchedOfficePackage.name) {
    diagnostics.push(diagnostic(
      "architecture.office-v2.public-entrypoint",
      file.path,
      `Office package imports must use the public package root ${matchedOfficePackage.name}.`,
      { package: rule.name, specifier },
    ));
    return;
  }
  const forbiddenKind = forbiddenSpecifierKind(specifier);
  if (forbiddenKind) {
    diagnostics.push(diagnostic(
      "architecture.office-v2.forbidden-import",
      file.path,
      `Office packages cannot import ${specifier}.`,
      { forbiddenKind, package: rule.name, specifier },
    ));
  } else if (rule.dependencies.includes(specifier)) {
    return;
  } else if (specifier.startsWith("@affiliate-ops/")) {
    diagnostics.push(diagnostic(
      "architecture.office-v2.import-direction",
      file.path,
      `Workspace import ${specifier} is outside the approved graph for ${rule.name}.`,
      { allowed: rule.dependencies, package: rule.name, specifier },
    ));
  } else {
    diagnostics.push(diagnostic(
      "architecture.office-v2.import-not-allowed",
      file.path,
      `Bare import ${specifier} is not approved for ${rule.name}.`,
      { allowed: rule.dependencies, package: rule.name, specifier },
    ));
  }
}

export function evaluateOfficeV2BoundaryInput(input) {
  const diagnostics = [];
  const presentRoots = new Set((input.presentRoots ?? []).map(normalizePath));
  const manifests = input.manifests ?? {};
  const files = (input.files ?? []).map((file) => ({ ...file, path: normalizePath(file.path) }));

  for (const rule of officeV2PackageRules) {
    if (!presentRoots.has(rule.root)) {
      diagnostics.push(diagnostic(
        "architecture.office-v2.missing-root",
        rule.root,
        "Approved Office package root is missing.",
        { package: rule.name },
      ));
    }
    validateManifest(rule, manifests[rule.root], diagnostics);
  }

  for (const file of files) {
    const rule = findOwningRule(file.path);
    const forbiddenModuleKind = rule ? forbiddenProjectModuleKind(file.path) : null;
    if (forbiddenModuleKind) {
      diagnostics.push(diagnostic(
        "architecture.office-v2.forbidden-module",
        file.path,
        `Office packages cannot contain ${forbiddenModuleKind} implementations.`,
        { forbiddenKind: forbiddenModuleKind, package: rule.name },
      ));
    }
    if (rule && file.path.endsWith(".schema.json")) {
      diagnostics.push(diagnostic(
        "architecture.office-v2.schema-duplicate",
        file.path,
        "Canonical Office schemas may exist only under docs/office-v2/schemas.",
        { package: rule.name },
      ));
    }
    if (
      file.path.startsWith("packages/office-v2-contracts/src/generated/") &&
      file.path.endsWith(".ts") &&
      !file.content.startsWith(generatedTypeHeader)
    ) {
      diagnostics.push(diagnostic(
        "architecture.office-v2.handwritten-generated-type",
        file.path,
        "Generated Office contract types must carry the generator ownership header.",
      ));
    }
    if (!sourceExtensions.has(extname(file.path))) continue;
    const moduleLoads = analyzeModuleLoads(file.content);
    if (rule && moduleLoads.some((entry) => !entry.literal)) {
      diagnostics.push(diagnostic(
        "architecture.office-v2.nonliteral-module-load",
        file.path,
        "Office package module loads must use a statically checkable string literal.",
        { package: rule.name },
      ));
    }
    const specifiers = new Set(
      moduleLoads.filter((entry) => entry.literal).map((entry) => entry.specifier),
    );
    for (const specifier of specifiers) {
      if (rule) validatePackageImport(file, rule, specifier, diagnostics);
      else if (file.path.startsWith(`${webFeatureRoot}/`)) {
        const officePackage = findOfficePackage(specifier);
        if (officePackage && specifier !== officePackage.name) {
          diagnostics.push(diagnostic(
            "architecture.office-v2.public-entrypoint",
            file.path,
            `Web composition must use the public package root ${officePackage.name}.`,
            { specifier },
          ));
        }
      }
    }
  }
  return diagnostics;
}

export function collectOfficeV2BoundaryInput(root = repositoryRoot) {
  const presentRoots = [];
  const manifests = {};
  const files = [];
  const rootsToScan = [...officeV2PackageRules.map((rule) => rule.root), webFeatureRoot];
  for (const projectRoot of rootsToScan) {
    const absoluteRoot = join(root, projectRoot);
    if (!existsSync(absoluteRoot)) continue;
    if (projectRoot.startsWith("packages/")) presentRoots.push(projectRoot);
    for (const absolute of collectFiles(absoluteRoot)) {
      const projectPath = normalizePath(relative(root, absolute));
      if (sourceExtensions.has(extname(projectPath)) || projectPath.endsWith(".schema.json")) {
        files.push({ path: projectPath, content: readFileSync(absolute, "utf8") });
      }
    }
  }
  for (const rule of officeV2PackageRules) {
    const manifestPath = join(root, rule.root, "package.json");
    if (!existsSync(manifestPath)) continue;
    try {
      manifests[rule.root] = { value: JSON.parse(readFileSync(manifestPath, "utf8")) };
    } catch (error) {
      manifests[rule.root] = { parseError: error.message };
    }
  }
  return { files, manifests, presentRoots };
}

export function evaluateOfficeV2Boundaries(root = repositoryRoot) {
  return evaluateOfficeV2BoundaryInput(collectOfficeV2BoundaryInput(root));
}

export function formatOfficeV2BoundaryDiagnostic(entry) {
  return `[${entry.code}] ${entry.path}: ${entry.message}`;
}
