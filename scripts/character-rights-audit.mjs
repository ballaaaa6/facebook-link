import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, relative, resolve } from "node:path";
import {
  validateCharacterRightsReview,
  validateCommercialCharacterRoster,
} from "../packages/contracts/src/characterRights.ts";

const root = resolve(import.meta.dirname, "..");
const charactersDir = join(root, "assets/game/characters");
const reviewPath = join(root, "assets/game/manifests/character-rights-review-v1.json");
const rosterPath = join(root, "assets/game/manifests/commercial-character-roster-v1.json");
const schemaPath = join(root, "assets/game/manifests/character-rights.schema.json");
const registryPath = join(charactersDir, "registry.json");
const auditPath = join(root, "assets/game/manifests/character-rights-audit-v1.json");
const reportPath = join(root, "docs/art/CHARACTER_RIGHTS_AUDIT.md");

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function projectPath(path) {
  return relative(root, path).replaceAll("\\", "/");
}

function sourceFile(directory, pet) {
  const candidates = [
    pet.spritesheetPath,
    "spritesheet.webp",
    "runtime-spritesheet-v2@2x.webp",
    "runtime-spritesheet-v2.webp",
  ].filter(Boolean);
  return candidates.map((name) => join(directory, name)).find(existsSync) ?? null;
}

function invert(mapping) {
  return new Map(Object.entries(mapping).map(([slot, slug]) => [slug, slot]));
}

function compare(path, expected, failures) {
  if (!existsSync(path)) failures.push(`Missing generated file: ${projectPath(path)}`);
  else if (readFileSync(path, "utf8") !== expected) failures.push(`Stale generated file: ${projectPath(path)}`);
}

function expectedUsage(id, agentRoles, companionRoles) {
  if (agentRoles.has(id)) return "active-agent-prototype";
  if (companionRoles.has(id)) return "active-companion-prototype";
  return "alternate-prototype";
}

function expectedSlot(id, agentRoles, companionRoles) {
  return agentRoles.get(id) ?? companionRoles.get(id) ?? null;
}

function auditMarkdown(audit) {
  const rows = audit.records.map((record) => (
    `| \`${record.id}\` | ${record.displayName} | ${record.usage} | ${record.replacementSlot ?? "—"} | ${record.disposition} |`
  ));
  return `# Character Rights Audit

Generated by \`scripts/character-rights-audit.mjs\`. Do not edit this report by hand.

## Status

- Audit status: \`${audit.status}\`
- Prototype records: ${audit.summary.prototypeRecords}
- Active prototype agents: ${audit.summary.activeAgentPrototypes}
- Active prototype companions: ${audit.summary.activeCompanionPrototypes}
- Deferred alternates: ${audit.summary.alternatePrototypes}
- Replacement production slots: ${audit.summary.productionSlots}
- Commercially approved replacements: ${audit.summary.commercialApprovedSlots}
- Unreviewed records: ${audit.summary.unreviewedRecords}

All reviewed prototype images remain internal-only and are forbidden as generation inputs. This audit does not grant rights to any prototype identity and does not activate the commercial roster.

## Reviewed Prototype Inventory

| Prototype | Display name | Usage | Replacement slot | Disposition |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

## Production Boundary

The replacement contract defines ten agent slots and one companion slot. Every replacement uses a new \`original-*\` identity, starts at \`planned\`, remains absent from Active Office, and requires explicit commercial reviewer sign-off before approval.
`;
}

function buildAudit(review, roster, registry, failures) {
  const agentRoles = invert(registry.agents);
  const companionRoles = invert(registry.companions);
  const directories = readdirSync(charactersDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const reviews = new Map(review.records.map((record) => [record.id, record]));
  const records = [];

  for (const id of directories) {
    const reviewed = reviews.get(id);
    if (!reviewed) {
      failures.push(`Unreviewed character directory: ${id}`);
      continue;
    }
    const usage = expectedUsage(id, agentRoles, companionRoles);
    const replacementSlot = expectedSlot(id, agentRoles, companionRoles);
    if (reviewed.usage !== usage) failures.push(`${id}: expected usage ${usage}, received ${reviewed.usage}`);
    if (reviewed.replacementSlot !== replacementSlot) {
      failures.push(`${id}: expected replacement slot ${replacementSlot ?? "null"}, received ${reviewed.replacementSlot ?? "null"}`);
    }
    if (reviewed.currentLicenseState !== registry.licenseStatus) {
      failures.push(`${id}: license state must match the active registry`);
    }
    const directory = join(charactersDir, id);
    const petPath = join(directory, "pet.json");
    if (!existsSync(petPath)) {
      failures.push(`${id}: missing pet.json`);
      continue;
    }
    const pet = readJson(petPath);
    const imagePath = sourceFile(directory, pet);
    if (!imagePath) failures.push(`${id}: no source spritesheet found`);
    records.push({
      id,
      displayName: pet.displayName ?? pet.name ?? id,
      usage,
      currentLicenseState: reviewed.currentLicenseState,
      permittedUse: reviewed.permittedUse,
      generationInputAllowed: reviewed.generationInputAllowed,
      disposition: reviewed.disposition,
      replacementSlot,
      sourceMetadata: projectPath(petPath),
      sourceImage: imagePath ? projectPath(imagePath) : null,
      sourceImageSha256: imagePath ? sha256(imagePath) : null,
      reviewStatus: reviewed.reviewStatus,
      reason: reviewed.reason,
    });
  }

  for (const id of reviews.keys()) {
    if (!directories.includes(id)) failures.push(`Review references an unknown character directory: ${id}`);
  }

  const expectedAgentSlots = new Set(Object.keys(registry.agents));
  const expectedCompanionSlots = new Set(Object.keys(registry.companions));
  for (const slot of roster.slots) {
    const expectedKind = expectedAgentSlots.has(slot.slotId)
      ? "agent"
      : expectedCompanionSlots.has(slot.slotId)
        ? "companion"
        : null;
    if (!expectedKind) failures.push(`Unknown production slot: ${slot.slotId}`);
    else if (slot.kind !== expectedKind) failures.push(`${slot.slotId}: expected kind ${expectedKind}`);
    if (directories.includes(slot.characterId)) failures.push(`${slot.slotId}: replacement ID reuses a prototype directory ID`);
  }
  const actualSlots = new Set(roster.slots.map((slot) => slot.slotId));
  for (const slot of [...expectedAgentSlots, ...expectedCompanionSlots]) {
    if (!actualSlots.has(slot)) failures.push(`Missing production slot: ${slot}`);
  }

  return {
    version: 1,
    generatedOn: review.reviewedOn,
    status: failures.length === 0 ? "accepted-rights-contract" : "invalid",
    inputs: {
      registry: projectPath(registryPath),
      review: projectPath(reviewPath),
      roster: projectPath(rosterPath),
      schema: projectPath(schemaPath),
    },
    summary: {
      prototypeRecords: records.length,
      activeAgentPrototypes: records.filter((record) => record.usage === "active-agent-prototype").length,
      activeCompanionPrototypes: records.filter((record) => record.usage === "active-companion-prototype").length,
      alternatePrototypes: records.filter((record) => record.usage === "alternate-prototype").length,
      replacementRequired: records.filter((record) => record.disposition === "replace-and-quarantine").length,
      productionSlots: roster.slots.length,
      commercialApprovedSlots: roster.slots.filter((slot) => slot.reviewStatus === "commercial-review-approved").length,
      unreviewedRecords: directories.length - records.length,
    },
    sourcePolicy: roster.sourcePolicy,
    records,
    productionSlots: roster.slots,
  };
}

const check = process.argv.includes("--check");
const failures = [];
for (const path of [reviewPath, rosterPath, schemaPath, registryPath]) {
  if (!existsSync(path)) failures.push(`Missing input: ${projectPath(path)}`);
}
if (failures.length === 0) {
  const review = readJson(reviewPath);
  const roster = readJson(rosterPath);
  const registry = readJson(registryPath);
  const schema = readJson(schemaPath);
  failures.push(...validateCharacterRightsReview(review), ...validateCommercialCharacterRoster(roster));
  if (schema.$id !== "character-rights.schema.json") failures.push("Character rights schema must keep its stable $id");
  const audit = buildAudit(review, roster, registry, failures);
  const auditText = `${JSON.stringify(audit, null, 2)}\n`;
  const reportText = auditMarkdown(audit);
  if (check) {
    compare(auditPath, auditText, failures);
    compare(reportPath, reportText, failures);
  } else if (failures.length === 0) {
    writeFileSync(auditPath, auditText);
    writeFileSync(reportPath, reportText);
  }
  if (failures.length === 0) {
    console.log(`Character rights audit OK: ${audit.summary.prototypeRecords} prototypes, ${audit.summary.productionSlots} replacement slots, ${audit.summary.commercialApprovedSlots} approved.`);
  }
}
if (failures.length > 0) {
  console.error(failures.map((failure) => `- ${failure}`).join("\n"));
  process.exitCode = 1;
}
